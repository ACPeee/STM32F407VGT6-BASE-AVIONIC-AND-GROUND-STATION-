int int_to_str(int num, char *str)
{
    int i = 0, j, temp;
    int sign = num;

    if(num == 0)
    {
        str[i++] = '0';
        str[i] = 0;
        return i;
    }

    if(sign < 0) num = -num;

    while(num)
    {
        str[i++] = num % 10 + '0';
        num /= 10;
    }

    if(sign < 0)
        str[i++] = '-';

    str[i] = 0;

    for(j = 0; j < i/2; j++)
    {
        temp = str[j];
        str[j] = str[i-j-1];
        str[i-j-1] = temp;
    }

    return i;
}
