        ptr += int_to_str((int)mpu_filter.gyro_z_filter, ptr);	*ptr++ = ',';
        ptr += int_to_str((int)temperature, ptr); *ptr++ = ',';
        ptr += int_to_str((int)pressure_bmp, ptr); *ptr++ = ',';
        ptr += int_to_str((int)altitude, ptr);

        *ptr++ = '\r';
        *ptr++ = '\n';

        int len = ptr - line;

        if(sd_ok)
        {
            f_write(&fil, line, len, &bw);
        }

        tx_data.packet_id = counter++;

        tx_data.accel_x =mpu_filter.accel_x_filter;

        tx_data.accel_y =mpu_filter.accel_y_filter;

        tx_data.accel_z =mpu_filter.accel_z_filter;

